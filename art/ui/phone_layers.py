"""Crop the slider phone's rendered layers (art/ui/slider_phone.py `layers`) to WebP for the game and write their
placement for the kit's Phone (web/components/gui/flat/phoneArt.ts).
    python3 art/ui/phone_layers.py <layers dir>
"""
import json, sys
from pathlib import Path
from PIL import Image

src = Path(sys.argv[1]); root = Path(__file__).resolve().parents[2]
out = root / "web/public/assets/ui/phone"; out.mkdir(parents=True, exist_ok=True)
meta = json.loads((src / "meta.json").read_text())
layers = {}
for name in ("base", "top", "charm"):
    im = Image.open(src / f"{name}.png").convert("RGBA")
    x0, y0, x1, y1 = im.getchannel("A").point(lambda a: 255 if a > 2 else 0).getbbox()
    im.crop((x0, y0, x1, y1)).save(out / f"{name}.webp", quality=86, alpha_quality=90, method=6)
    layers[name] = [x0, y0, x1 - x0, y1 - y0]
    print(name, layers[name], (out / f"{name}.webp").stat().st_size, "bytes")

art = {"canvas": meta["canvas"], "body": meta["body"][1], "layers": layers, "screen": meta["screen"], "slide": meta["slide"], "pivot": meta["pivot"]}
(root / "web/components/gui/flat/phoneArt.ts").write_text(
    "// Generated by art/ui/phone_layers.py from art/ui/slider_phone.py: where the slider phone's rendered layers sit,\n"
    "// in pixels of its render canvas (the open phone's bounds). Don't edit by hand; rerun the two scripts.\n"
    f"export const PHONE_ART = {json.dumps(art, separators=(', ', ': '))} as const;\n")
